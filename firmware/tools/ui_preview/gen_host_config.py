#!/usr/bin/env python3
"""Copy the firmware's LVGL Kconfig values (build/config/sdkconfig.h) into a header the
host build includes, so the preview renders with exactly the firmware's LVGL options.

Usage: gen_host_config.py <build/config/sdkconfig.h> <out host_sdkconfig.h>
"""
import sys

src, out = sys.argv[1], sys.argv[2]
keep = [l for l in open(src, encoding="utf-8") if l.startswith("#define CONFIG_LV_")]
# The firmware already uses LV_OS_NONE and no assembly; refuse anything host-incompatible.
bad = [l for l in keep if l.split()[1] in ("CONFIG_LV_OS_FREERTOS", "CONFIG_LV_DRAW_SW_ASM_RISCV_V")]
if bad:
    sys.exit("unsupported for host preview: " + ", ".join(l.split()[1] for l in bad))
# Host pointers are 64-bit, so the same widgets need about twice the LVGL heap the
# 32-bit device uses. Only the heap size differs; every visual option is copied as-is.
keep = ["#define CONFIG_LV_MEM_SIZE_KILOBYTES 256\n" if l.startswith("#define CONFIG_LV_MEM_SIZE_KILOBYTES ")
        else l for l in keep]
open(out, "w", encoding="utf-8").write(
    "/* Generated by tools/ui_preview/gen_host_config.py from the firmware build. */\n"
    "#pragma once\n" + "".join(keep))
print(f"{out}: {len(keep)} LVGL options")
