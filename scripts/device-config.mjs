#!/usr/bin/env node
// 生成固件里的 main/hw_secrets.h：设备怎么找到这台电脑（电脑名、备用 IP、端口）以及设备令牌。
// 用法：node scripts/device-config.mjs <固件目录> [端口]
// 令牌来自作业助手的数据目录（~/.dsh/homework-helper/device_token），插件第一次启动时生成。
// 这个文件含令牌，固件仓库的 .gitignore 已排除它；本脚本也不会把令牌打印出来。
import { execFileSync } from 'node:child_process'
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir, hostname, networkInterfaces } from 'node:os'
import { join, resolve } from 'node:path'

const fw = process.argv[2] && resolve(process.argv[2])
const port = Number(process.argv[3]) || 8787
if (!fw || !existsSync(join(fw, 'main'))) {
  console.error('用法：node scripts/device-config.mjs <固件目录> [端口]（固件目录里要有 main/）')
  process.exit(1)
}
const tokenFile = join(process.env.HOMEWORK_DATA_DIR || join(homedir(), '.dsh', 'homework-helper'), 'device_token')
if (!existsSync(tokenFile)) {
  console.error(`还没有设备令牌（${tokenFile}）：先在 DeepSeek Harness 里启用作业助手插件，让它启动一次。`)
  process.exit(1)
}

// 电脑名：macOS 用 Bonjour 名（设备用 <名字>.local 找电脑），其他系统用主机名
let host = ''
try { host = execFileSync('scutil', ['--get', 'LocalHostName'], { encoding: 'utf8' }).trim() } catch { /* 不是 macOS */ }
host ||= hostname().replace(/\.local$/, '')

// 备用 IP：第一个私有网段的 IPv4 地址（电脑名解析不了时用）
const ip = Object.values(networkInterfaces()).flat()
  .find((a) => a && a.family === 'IPv4' && !a.internal && /^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.)/.test(a.address))?.address || '0.0.0.0'

const token = readFileSync(tokenFile, 'utf8').trim()
const out = join(fw, 'main', 'hw_secrets.h')
writeFileSync(out, [
  '// Generated by albis-aipassport-homework/scripts/device-config.mjs. Git-ignored; holds the device token.',
  '#pragma once',
  '',
  `#define HW_RELAY_HOSTNAME    "${host}"`,
  `#define HW_RELAY_FALLBACK_IP "${ip}"`,
  `#define HW_RELAY_PORT        ${port}`,
  `#define HW_DEVICE_TOKEN      "${token}"`,
  '',
].join('\n'))
chmodSync(out, 0o600)
console.log(`已写入 ${out}\n电脑名 ${host}.local，备用 IP ${ip}，端口 ${port}（令牌已写入，不在这里显示）`)
